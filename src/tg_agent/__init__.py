"""ТГ-агент: Джесси пишет или наговаривает боту, что сделать на ноуте —
агент смотрит на экран, двигает мышь по-человечески, кликает, печатает
и отчитывается в чат. Отдельный процесс, с мостом Джарвиса не пересекается."""


def console_utf8() -> None:
    """Заставить stdout/stderr принимать не-ASCII.

    Консоль Windows по умолчанию cp1252, а все наши сообщения русские: первый
    же print с ошибкой падал бы UnicodeEncodeError — то есть ровно там, где
    человеку нужен текст, он получал бы трейсбек вместо объяснения.
    errors="replace", а не "strict": лучше «?» вместо буквы, чем упавший CLI.

    Зовётся явно из точек входа, а не по импорту: побочные эффекты при импорте
    библиотеки — плохой тон, а точек входа у нас всего две.
    """
    for stream in (__import__("sys").stdout, __import__("sys").stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(encoding="utf-8", errors="replace")
        except (ValueError, OSError):
            pass  # поток перенаправлен во что-то, что так не умеет — не беда
